// Região aproximada para a placa da câmera
export function regionOf(x, y, z) {
  if (z > 900 || z < -80) return 'Interior';
  if (x > 44 && y < -768 && x < 3000) return 'Los Santos';
  if (x < -1000 && y > -1000 && y < 1650 && x > -3000) return 'San Fierro';
  if (x > 869 && y > 596) return 'Las Venturas';
  if (Math.abs(x) > 3000 || Math.abs(y) > 3000) return 'Mar aberto';
  if (x < -1000 && y > 1650) return 'Tierra Robada';
  if (x < -600 && y < -1000) return 'Whetstone';
  if (x < 869 && y > 596) return 'Bone County';
  if (y < -768) return 'Flint County';
  return 'Red County';
}
